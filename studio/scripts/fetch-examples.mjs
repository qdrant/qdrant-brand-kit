// Downloads shadcn's official Base UI example for every component in design-system/components/ui,
// rewrites its imports to this repo's packages, and writes it to an output folder (default: studio/examples).
// The examples are shadcn/ui's (MIT License, see examples/LICENSE-shadcn.md). Re-run after adding components.
//
//   node studio/scripts/fetch-examples.mjs [output folder]
//
// No dependencies. Prints any import it doesn't know how to rewrite, so nothing breaks silently.

import { readdirSync, mkdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const OUT = resolve(process.argv[2] ?? join(ROOT, "studio", "examples"))
const BASE = "https://ui.shadcn.com/code/apps/v4/registry/bases/base/examples"

const rewrites = [
  [/@\/registry\/bases\/base\/components\/example/g, "@/components/example"],
  [/@\/app\/\(create\)\/components\/icon-placeholder/g, "@/components/icon-placeholder"],
  [/@\/registry\/bases\/base\/ui\//g, "@qdrant/design-system/components/ui/"],
  [/@\/registry\/bases\/base\/lib\//g, "@qdrant/design-system/lib/"],
  [/@\/registry\/bases\/base\/hooks\//g, "@qdrant/design-system/hooks/"],
  [/@\/components\/ui\//g, "@qdrant/design-system/components/ui/"],
]

// Examples that need shadcn's own site code (AI SDK sample data), so they aren't fetched yet.
const SKIP = new Set(["code-block", "message", "message-scroller", "trace"])

const components = readdirSync(join(ROOT, "design-system", "components", "ui"))
  .filter((f) => f.endsWith(".tsx"))
  .map((f) => f.replace(/\.tsx$/, ""))
  .sort()

mkdirSync(OUT, { recursive: true })
const found = []
const missing = []
const unknown = []
const skipped = []
for (const name of components) {
  if (SKIP.has(name)) {
    skipped.push(name)
    continue
  }
  const res = await fetch(`${BASE}/${name}-example.tsx`)
  if (!res.ok) {
    missing.push(name)
    continue
  }
  let code = await res.text()
  for (const [from, to] of rewrites) code = code.replace(from, to)
  for (const m of code.matchAll(/from\s+"(@\/[^"]+)"/g)) {
    if (!["@/components/example", "@/components/icon-placeholder"].includes(m[1])) unknown.push(`${name}: ${m[1]}`)
  }
  writeFileSync(join(OUT, `${name}.tsx`), `// From shadcn/ui (MIT License, see LICENSE-shadcn.md), fetched by studio/scripts/fetch-examples.mjs.\n${code}`)
  found.push(name)
}
// An index the studio loads examples from, one lazy import per component.
writeFileSync(
  join(OUT, "index.ts"),
  `// Generated by studio/scripts/fetch-examples.mjs. Do not edit by hand.\nimport type { ComponentType } from "react"\n\nexport const examples: Record<string, () => Promise<{ default: ComponentType }>> = {\n${found.map((n) => `  "${n}": () => import("./${n}"),`).join("\n")}\n}\n`
)
console.log(`Wrote ${found.length} examples to ${OUT}`)
if (skipped.length) console.log(`Skipped (need shadcn's AI sample code): ${skipped.join(", ")}`)
if (missing.length) console.log(`No example on shadcn for: ${missing.join(", ")}`)
if (unknown.length) {
  console.log(`Imports to fix by hand:\n  ${unknown.join("\n  ")}`)
  process.exitCode = 1
}
