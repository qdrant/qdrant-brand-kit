// Downloads shadcn's official Base UI example for every component in design-system/components/ui, and
// the cards of shadcn's Create page preview (the preview-02 block), rewrites their imports to this repo's
// packages, and writes them to an output folder (default: studio/examples, the block in its preview/ folder).
// They are shadcn/ui's (MIT License, see examples/LICENSE-shadcn.md). Re-run after adding components.
//
//   node studio/scripts/fetch-examples.mjs [output folder]
//
// No dependencies. Prints any import it doesn't know how to rewrite, so nothing breaks silently.

import { readdirSync, mkdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const OUT = resolve(process.argv[2] ?? join(ROOT, "studio", "examples"))
const BASE = "https://ui.shadcn.com/code/apps/v4/registry/bases/base/examples"
const BLOCK = "https://ui.shadcn.com/code/apps/v4/registry/bases/base/blocks/preview-02"

const rewrites = [
  [/@\/registry\/bases\/base\/components\/example/g, "@/components/example"],
  [/@\/app\/\(create\)\/components\/icon-placeholder/g, "@/components/icon-placeholder"],
  [/@\/registry\/bases\/base\/ui\//g, "@qdrant/design-system/components/ui/"],
  [/@\/registry\/bases\/base\/lib\//g, "@qdrant/design-system/lib/"],
  [/@\/registry\/bases\/base\/hooks\//g, "@qdrant/design-system/hooks/"],
  [/@\/components\/ui\//g, "@qdrant/design-system/components/ui/"],
  // The preview block: its cards sit next to it, and they ask shadcn's site which style is active.
  [/@\/registry\/bases\/base\/blocks\/preview-02\/cards\//g, "./cards/"],
  [/@\/app\/\(app\)\/create\/lib\/search-params/g, "@/lib/design-system-params"],
  // shadcn's site switches classes per style with style-*: variants. The design system is base-mira, so
  // mira's win (marked important over the classes they replace), the other styles' go, and so does the
  // site's heading font class (headings use Mona Sans like everything else).
  [/\bstyle-mira:([^\s"'`]+)/g, "$1!"],
  [/ ?\bstyle-[a-z]+:[^\s"'`]+/g, ""],
  [/ ?\bcn-font-heading\b/g, ""],
]
const KNOWN = ["@/components/example", "@/components/icon-placeholder", "@/lib/design-system-params"]
const HEADER = "// From shadcn/ui (MIT License, see LICENSE-shadcn.md), fetched by studio/scripts/fetch-examples.mjs.\n"

function rewrite(code, label) {
  for (const [from, to] of rewrites) code = code.replace(from, to)
  for (const m of code.matchAll(/from\s+"(@\/[^"]+)"/g)) {
    if (!KNOWN.includes(m[1])) unknown.push(`${label}: ${m[1]}`)
  }
  return code
}

// Examples that need shadcn's own site code (AI SDK sample data), so they aren't fetched yet.
const SKIP = new Set(["code-block", "message", "message-scroller", "trace"])

const components = readdirSync(join(ROOT, "design-system", "components", "ui"))
  .filter((f) => f.endsWith(".tsx"))
  .map((f) => f.replace(/\.tsx$/, ""))
  .sort()

mkdirSync(OUT, { recursive: true })
const found = []
const missing = []
const unknown = []
const skipped = []
for (const name of components) {
  if (SKIP.has(name)) {
    skipped.push(name)
    continue
  }
  const res = await fetch(`${BASE}/${name}-example.tsx`)
  if (!res.ok) {
    missing.push(name)
    continue
  }
  const code = rewrite(await res.text(), name)
  writeFileSync(join(OUT, `${name}.tsx`), `${HEADER}${code}`)
  found.push(name)
}
// An index the studio loads examples from, one lazy import per component.
writeFileSync(
  join(OUT, "index.ts"),
  `// Generated by studio/scripts/fetch-examples.mjs. Do not edit by hand.\nimport type { ComponentType } from "react"\n\nexport const examples: Record<string, () => Promise<{ default: ComponentType }>> = {\n${found.map((n) => `  "${n}": () => import("./${n}"),`).join("\n")}\n}\n`
)
console.log(`Wrote ${found.length} examples to ${OUT}`)

// shadcn's Create page preview: one block that lays out cards using many components at once.
async function get(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} for ${url}`)
  return res.text()
}
const blockIndex = await get(`${BLOCK}/index.tsx`)
const cards = [...new Set([...blockIndex.matchAll(/blocks\/preview-02\/cards\/([a-z0-9-]+)"/g)].map((m) => m[1]))]
mkdirSync(join(OUT, "preview", "cards"), { recursive: true })
for (const card of cards) {
  const code = rewrite(await get(`${BLOCK}/cards/${card}.tsx`), `preview/${card}`)
  writeFileSync(join(OUT, "preview", "cards", `${card}.tsx`), `${HEADER}${code}`)
}
// The cards use state, so the block runs in the browser.
const index = rewrite(blockIndex, "preview/index").replace(/^(?!"use client")/, '"use client"\n\n')
writeFileSync(join(OUT, "preview", "index.tsx"), `${HEADER}${index}`)
console.log(`Wrote the Create page preview (${cards.length} cards) to ${join(OUT, "preview")}`)
if (skipped.length) console.log(`Skipped (need shadcn's AI sample code): ${skipped.join(", ")}`)
if (missing.length) console.log(`No example on shadcn for: ${missing.join(", ")}`)
if (unknown.length) {
  console.log(`Imports to fix by hand:\n  ${unknown.join("\n  ")}`)
  process.exitCode = 1
}
